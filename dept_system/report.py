from .config import BASE_DIR, STATE_NAMES


def write_conclusion(df, metrics, comp, example_text, path=BASE_DIR / "output" / "conclusion.md"):
    dist = df["state"].value_counts(normalize=True).sort_index() * 100
    txt = f"""# Итоговый управленческий вывод

**Данные.** Сформирован воспроизводимый набор из {len(df)} наблюдений
({df['department'].nunique()} подразделений × {df['period'].nunique()} месяцев, seed фиксирован).
Распределение состояний: проблемное — {dist.get(0, 0):.1f}%, требует внимания — {dist.get(1, 0):.1f}%,
устойчивое — {dist.get(2, 0):.1f}%. Состояние определяется по балльной формуле
(рентабельность, выполнение плана, просрочки, дефекты; убыток всегда дает «проблемное»).

**Нечеткая модель.** Четыре входа по три терма, 18 экспертных правил, вывод Mamdani с центроидом.
Модель прозрачна: для каждого решения видно, какие правила сработали. На тесте она совпала с
учебной разметкой в {comp['fuzzy_acc']:.1%} случаев (F1 macro = {comp['fuzzy_f1']:.3f}).

**Нейронная сеть.** MLPClassifier (32-16), разбиение 80/20 со стратификацией, масштабирование
StandardScaler обучено только на train. Тест: Accuracy = {metrics['accuracy']:.3f},
Precision = {metrics['precision']:.3f}, Recall = {metrics['recall']:.3f}, F1 = {metrics['f1']:.3f}.
Основные ошибки возникают на границе соседних классов (см. матрицу ошибок).

**Сравнение.** Модели дают одинаковый ответ в {comp['agree']:.1%} случаев. Нейросеть точнее,
нечеткая модель понятнее для руководителя и не требует обучающих данных.

**Рекомендации руководству.**
1. «Устойчивое» — поддерживать текущий режим, контролировать динамику рентабельности.
2. «Требует внимания» — выявить зону риска (просрочки, дефекты или план) и поставить срок устранения.
3. «Проблемное» — оперативный разбор причин, план антикризисных мер, ежемесячный контроль.
4. Если модели расходятся — не принимать решение автоматически, а запросить экспертную проверку.

**Пример оценки нового подразделения.**

```
{example_text}
```

**Ограничения.** Данные синтетические, а целевая переменная построена по формуле, поэтому высокая
точность моделей говорит о воспроизведении этой формулы, а не о прогнозе реальной ситуации.
На реальных данных нужна проверка на отложенном периоде и калибровка порогов.
"""
    path.parent.mkdir(exist_ok=True)
    path.write_text(txt, encoding="utf-8")
    return str(path)
